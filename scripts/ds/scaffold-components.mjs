// design/figma/{components,screens}.json → the component scaffold.
//
// Per component, in src/renderer/src/components/<Name>/:
//   <Name>.types.ts     GENERATED every run — the Figma contract (props, unions, defaults)
//   index.ts            GENERATED every run
//   <Name>.tsx          created once — ScaffoldStub body until ported (then yours)
//   <Name>.variants.ts  created once — cva with an empty class slot per variant option
//   <Name>.test.tsx     created once — renders every variant × state combination
// Plus (GENERATED): components/index.ts, design-system/catalog.generated.ts,
// design-system/screens.generated.ts.
//
// Run: pnpm ds:scaffold          write / refresh
//      pnpm ds:scaffold --check  exit 1 if anything generated is stale, a component is
//                                missing, a folder is orphaned or a variants file lacks an option
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import prettier from 'prettier'
import { FIGMA_ONLY, NOT_IN_CODE, ROOT, camel, loadContracts, loadSnapshot, pascal } from './contract.mjs'

const CHECK = process.argv.includes('--check')
const RENDERER = resolve(ROOT, 'src/renderer/src')
const COMPONENTS = resolve(RENDERER, 'components')
const DS = resolve(RENDERER, 'design-system')
const GENERATED =
  '// GENERATED by scripts/ds/scaffold-components.mjs from design/figma — do not edit.\n'
const prettierConfig = {
  ...(await prettier.resolveConfig(resolve(ROOT, 'package.json'))),
  parser: 'typescript'
}

const contracts = loadContracts()
const problems = []
const written = []

const q = (s) => JSON.stringify(s)
const key = (s) => (/^[A-Za-z_$][\w$]*$/.test(s) ? s : q(s))
const upper = (name) => name.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toUpperCase()
const iconExport = (name) => `${pascal(name)}Icon`
const doc = (text) => `/** ${text.replace(/\*\//g, '*\\/')} */`

async function emit(path, source, { once = false } = {}) {
  const formatted = await prettier.format(source, prettierConfig)
  const exists = existsSync(path)
  if (once && exists) return
  const current = exists ? readFileSync(path, 'utf8') : null
  if (current === formatted) return
  const rel = path.replace(ROOT + '/', '')
  if (CHECK) {
    problems.push(`${exists ? 'stale' : 'missing'}: ${rel}`)
    return
  }
  mkdirSync(resolve(path, '..'), { recursive: true })
  writeFileSync(path, formatted)
  written.push(rel)
}

// ---------------------------------------------------------------- per component
function typesFile(c) {
  const U = upper(c.name)
  const icons = [...new Set(Object.values(c.icons))]
  const hasSlots = Object.keys(c.slots).length > 0
  const L = [GENERATED]
  if (hasSlots) L.push(`import type { ReactNode } from 'react'`)
  if (icons.length) {
    L.push(`import type { IconSvgElement } from '@hugeicons/react'`)
    L.push(`import { ${icons.map(iconExport).join(', ')} } from '@hugeicons/core-free-icons'`)
  }
  L.push(`import type { ComponentContract } from '@renderer/design-system/contract'`, '')

  const contract = {
    name: c.name,
    figmaName: c.figmaName,
    figmaId: c.figmaId,
    figmaUrl: c.figmaUrl,
    section: c.section,
    description: c.description,
    code: c.code,
    axes: c.axes,
    axisDefaults: c.axisDefaults,
    flags: c.flags,
    interactionStates: c.interactionStates,
    disabled: c.disabled,
    booleans: c.booleans,
    texts: c.texts,
    icons: c.icons,
    slots: c.slots
  }
  L.push(
    `export const ${U}_CONTRACT = ${JSON.stringify(contract, null, 2)} as const satisfies ComponentContract`,
    ''
  )

  for (const [axis, options] of Object.entries(c.axes)) {
    L.push(`export type ${c.name}${pascal(axis)} = ${options.map(q).join(' | ')}`)
  }
  const propCount =
    Object.keys(c.axes).length +
    Object.keys(c.flags).length +
    Number(c.disabled) +
    Object.keys(c.booleans).length +
    Object.keys(c.texts).length +
    Object.keys(c.icons).length +
    Object.keys(c.slots).length
  if (propCount === 0) {
    L.push(
      '',
      `/** No Figma properties. */`,
      `export type ${c.name}ContractProps = Record<never, never>`,
      ''
    )
  } else L.push('', `export interface ${c.name}ContractProps {`)
  for (const [axis, options] of Object.entries(c.axes)) {
    L.push(
      `  ${doc(`Figma \`${axis}\` (${options.length} options). Default \`${c.axisDefaults[axis]}\`.`)}`
    )
    L.push(`  ${key(axis)}?: ${c.name}${pascal(axis)}`)
  }
  for (const [flag, { on, off }] of Object.entries(c.flags)) {
    L.push(
      `  ${doc(`Figma \`state=${on}\` (false = \`state=${off}\`).`)}`,
      `  ${key(flag)}?: boolean`
    )
  }
  if (c.disabled) L.push(`  ${doc('Figma `state=disabled`.')}`, `  disabled?: boolean`)
  for (const [b, def] of Object.entries(c.booleans)) {
    L.push(`  ${doc(`Figma boolean. Default \`${def}\`.`)}`, `  ${key(b)}?: boolean`)
  }
  for (const [t, def] of Object.entries(c.texts)) {
    L.push(`  ${doc(`Figma text. Default ${q(def)}.`)}`, `  ${key(t)}?: string`)
  }
  for (const [i, def] of Object.entries(c.icons)) {
    L.push(`  ${doc(`Figma icon swap. Default \`${def}\`.`)}`, `  ${key(i)}?: IconSvgElement`)
  }
  for (const [s, component] of Object.entries(c.slots)) {
    const what = component === 'content' ? 'free content slot' : `nests \`${component}\` in Figma`
    L.push(`  ${doc(`Slot — ${what}.`)}`, `  ${key(s)}?: ReactNode`)
  }
  if (propCount > 0) L.push('}', '')

  const defaults = [
    ...Object.entries(c.axisDefaults).map(([k, v]) => `${key(k)}: ${q(v)}`),
    ...Object.keys(c.flags).map((k) => `${key(k)}: false`),
    ...(c.disabled ? ['disabled: false'] : []),
    ...Object.entries(c.booleans).map(([k, v]) => `${key(k)}: ${v}`),
    ...Object.entries(c.texts).map(([k, v]) => `${key(k)}: ${q(v)}`),
    ...Object.entries(c.icons).map(([k, v]) => `${key(k)}: ${iconExport(v)}`)
  ]
  L.push(`/** Figma defaults. Slots have none. */`)
  L.push(
    `export const ${U}_DEFAULTS = {\n${defaults.map((d) => `  ${d},`).join('\n')}\n} satisfies ${c.name}ContractProps`
  )
  return L.join('\n')
}

function variantsFile(c) {
  const fn = `${camel(c.name)}Variants`
  const groups = [
    ...Object.entries(c.axes).map(
      ([axis, options]) =>
        `    ${key(axis)}: {\n${options.map((o) => `      ${key(o)}: '',`).join('\n')}\n    },`
    ),
    ...Object.keys(c.flags).map((flag) => `    ${key(flag)}: { true: '', false: '' },`)
  ]
  const defaults = [
    ...Object.entries(c.axisDefaults).map(([k, v]) => `${key(k)}: ${q(v)}`),
    ...Object.keys(c.flags).map((k) => `${key(k)}: false`)
  ]
  const config = groups.length
    ? `, {\n  variants: {\n${groups.join('\n')}\n  },\n  defaultVariants: { ${defaults.join(', ')} },\n}`
    : ''
  return `import { cva } from 'class-variance-authority'

// TODO(port): fill every class slot from Figma — ${c.figmaUrl}
// Colours: the Figma token name (bg-surface-3, text-tertiary, border-focus…) except the five
// shadcn owns — text-foreground, text-muted-foreground, bg-primary, border-primary, border-input.
// Type: type-<role>-<size>-<weight>. States: hover: focus-visible: active: disabled: (never variants).
// shadcn-backed primitive? Restyle ui/ instead and make this component a thin adapter (design/README.md).
export const ${fn} = cva(''${config})
`
}

function componentFile(c) {
  const U = upper(c.name)
  const cvaArgs = [...Object.keys(c.axes), ...Object.keys(c.flags)].map(
    (k) => `${key(k)}: props.${k}`
  )
  const today = c.code ? `\n * Today: ${c.code}` : ''
  return `import { ScaffoldStub } from '@renderer/design-system/ScaffoldStub'
import { cn } from '@renderer/lib/utils'
import { ${U}_CONTRACT, ${U}_DEFAULTS, type ${c.name}ContractProps } from './${c.name}.types'
import { ${camel(c.name)}Variants } from './${c.name}.variants'

export interface ${c.name}Props extends ${c.name}ContractProps {
  className?: string
}

/**
 * ${c.name} — ${c.description.replace(/\*\//g, '*\\/')}
 * Figma: ${c.figmaUrl}${today}
 */
export function ${c.name}({ className, ...rest }: ${c.name}Props) {
  const props = { ...${U}_DEFAULTS, ...rest }
  // TODO(port): replace ScaffoldStub with the real markup. Keep the props contract and
  // data-ds="${c.name}" on the root element.
  return (
    <ScaffoldStub
      contract={${U}_CONTRACT}
      props={props}
      className={cn(${camel(c.name)}Variants(${cvaArgs.length ? `{ ${cvaArgs.join(', ')} }` : ''}), className)}
    />
  )
}
`
}

function testFile(c) {
  const U = upper(c.name)
  const hasTexts = Object.keys(c.texts).length > 0
  const textTest = hasTexts
    ? `

  it('renders the Figma default text', () => {
    render(<${c.name} />)
    for (const text of Object.values<string>(${U}_CONTRACT.texts)) {
      expect(screen.getAllByText(text).length).toBeGreaterThan(0)
    }
  })`
    : ''
  return `import { describe, expect, it } from 'vitest'
import { render${hasTexts ? ', screen' : ''} } from '@testing-library/react'
import { variantMatrix } from '@renderer/design-system/matrix'
import { ${c.name}, type ${c.name}Props } from './${c.name}'
import { ${U}_CONTRACT } from './${c.name}.types'

describe('${c.name}', () => {
  it.each(variantMatrix(${U}_CONTRACT))('renders %s', (_label, props) => {
    const { baseElement } = render(<${c.name} {...(props as ${c.name}Props)} />)
    expect(baseElement.querySelector('[data-ds="${c.name}"]')).not.toBeNull()
  })${textTest}
})
`
}

const indexFile = (c) =>
  `${GENERATED}export * from './${c.name}'\nexport * from './${c.name}.types'\nexport * from './${c.name}.variants'\n`

function checkVariantsCoverage(c) {
  const path = resolve(COMPONENTS, c.name, `${c.name}.variants.ts`)
  if (!existsSync(path)) return
  const src = readFileSync(path, 'utf8')
  for (const [axis, options] of Object.entries(c.axes)) {
    for (const o of options) {
      const slot = new RegExp(`[\\s{,]['"]?${o.replace(/[-]/g, '\\-')}['"]?\\s*:`)
      if (!slot.test(src)) problems.push(`variants: ${c.name}.${axis} has no class slot for '${o}'`)
    }
  }
}

const isStub = (c) => {
  const path = resolve(COMPONENTS, c.name, `${c.name}.tsx`)
  return !existsSync(path) || readFileSync(path, 'utf8').includes('ScaffoldStub')
}

for (const c of contracts) {
  const dir = resolve(COMPONENTS, c.name)
  await emit(resolve(dir, `${c.name}.types.ts`), typesFile(c))
  await emit(resolve(dir, 'index.ts'), indexFile(c))
  await emit(resolve(dir, `${c.name}.tsx`), componentFile(c), { once: true })
  await emit(resolve(dir, `${c.name}.variants.ts`), variantsFile(c), { once: true })
  await emit(resolve(dir, `${c.name}.test.tsx`), testFile(c), { once: true })
  checkVariantsCoverage(c)
}

// ---------------------------------------------------------------- barrels + catalog
const names = contracts.map((c) => c.name)
await emit(
  resolve(COMPONENTS, 'index.ts'),
  GENERATED + names.map((n) => `export * from './${n}'`).join('\n') + '\n'
)

await emit(
  resolve(DS, 'catalog.generated.ts'),
  `${GENERATED}import type { ComponentType } from 'react'
import type { ComponentContract } from './contract'
${contracts.map((c) => `import { ${c.name}, ${upper(c.name)}_CONTRACT } from '@renderer/components/${c.name}'`).join('\n')}

export interface CatalogEntry {
  contract: ComponentContract
  component: ComponentType<Record<string, unknown>>
}

const entry = (contract: ComponentContract, component: unknown): CatalogEntry => ({
  contract,
  component: component as ComponentType<Record<string, unknown>>
})

export const CATALOG: CatalogEntry[] = [
${contracts.map((c) => `  entry(${upper(c.name)}_CONTRACT, ${c.name}),`).join('\n')}
]
`
)

const screens = loadSnapshot('screens.json')
const codeName = (figmaName) => pascal(figmaName)
await emit(
  resolve(DS, 'screens.generated.ts'),
  `${GENERATED}export interface ScreenEntry {
  title: string
  figmaId: string
  flow: string
  /** The ↳ Figma page the screen lives on (one per journey stage). */
  page: string
  /** Code names of the design-system components the screen composes. */
  components: string[]
}

export const FIGMA_FLOWS_URL = ${q(`https://www.figma.com/design/${screens.source.fileKey}/DesignStash?node-id=${screens.source.flowsPage.replace(':', '-')}`)}

/** figmaId of each screen on the prototype's happy path, in order. */
export const HAPPY_PATH: string[] = ${JSON.stringify(screens.prototype.happyPath)}

export const SCREENS: ScreenEntry[] = ${JSON.stringify(
    screens.screens.map((s) => ({
      title: s.title,
      figmaId: s.figmaId,
      flow: s.flow,
      page: s.page,
      components: s.components
        .filter((n) => !FIGMA_ONLY.has(n) && !NOT_IN_CODE.has(n))
        .map(codeName)
    })),
    null,
    2
  )}
`
)

// ---------------------------------------------------------------- drift report
const screenIds = new Set(screens.screens.map((s) => s.figmaId))
for (const id of [screens.prototype.start, ...screens.prototype.happyPath])
  if (!screenIds.has(id))
    problems.push(`dangling: prototype screen ${id} is not in design/figma/screens.json`)
const known = new Set(names)
for (const entry of readdirSync(COMPONENTS, { withFileTypes: true })) {
  if (entry.isDirectory() && !known.has(entry.name))
    problems.push(`orphan: components/${entry.name} is not in design/figma/components.json`)
}

const stubs = contracts.filter(isStub).length
if (CHECK) {
  if (problems.length) {
    console.error(
      `ds:scaffold --check found ${problems.length} problem(s):\n  ${problems.join('\n  ')}\nRun pnpm ds:scaffold.`
    )
    process.exit(1)
  }
  console.log(
    `ds:scaffold --check ok — ${contracts.length} components`
  )
} else {
  for (const p of problems) console.warn(`warn  ${p}`)
  console.log(
    `ds:scaffold — ${written.length} file(s) written · ${contracts.length} components · ${stubs} stubs`
  )
}
