// design/figma/tokens.json → src/renderer/src/styles/{tokens,theme,shadcn-bridge}.css
//                           + src/renderer/src/design-system/tokens.generated.ts
//
// How Figma tokens reach Tailwind without bending shadcn:
//
//   shadcn's own variables (--primary, --background, --muted-foreground, --border…) stay
//   the contract for everything in ui/ — including components added later with
//   `shadcn add`. shadcn-bridge.css points those variables at Figma tokens; assets/main.css
//   imports it, so every ui/ component takes its colours from the Figma tokens.
//
//   Figma tokens shadcn has no name for become ordinary Tailwind colours, scoped the way
//   Figma scopes them: background/X → bg-X, text/X → text-X, border/X → border-X
//   (Tailwind's --background-color-* / --text-color-* / --border-color-* namespaces).
//   Names shadcn owns are never redefined — those Figma tokens are used through the
//   shadcn name instead (text/primary → text-foreground). See SHADCN below.
//
//   tokens.css          :root --ds-* custom properties (primitives + semantic aliases)
//   theme.css           Tailwind keys for the Figma-only names, font families, type-* utilities
//   shadcn-bridge.css   shadcn variables → Figma tokens
//   tokens.generated.ts token data for the DEV catalog (incl. the class to use for each token)
//
// Run: pnpm ds:tokens   (never edit the generated files by hand)
import { mkdirSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import prettier from 'prettier'
import { ROOT, loadSnapshot } from './contract.mjs'

const snap = loadSnapshot('tokens.json')
const OUT = resolve(ROOT, 'src/renderer/src/styles')
mkdirSync(OUT, { recursive: true })
const HEADER = `/* GENERATED by scripts/ds/build-tokens.mjs from design/figma/tokens.json — do not edit. */\n`

const v = (figmaName) => `--ds-${figmaName.replace(/\//g, '-').replace(/_/g, '-')}`
// A number token is px unless it names another unit (ms for durations, '' for unitless strokes).
const withUnit = (t) => `${t.value}${t.unit ?? 'px'}`

/**
 * shadcn variable → Figma token. The only place the two vocabularies meet.
 * `use` = the utility code writes for a Figma token whose own name shadcn already owns.
 */
const SHADCN = {
  background: { token: 'background/surface-1' },
  foreground: { token: 'text/primary', use: 'text-foreground' },
  card: { token: 'background/surface-3' },
  'card-foreground': { token: 'text/primary' },
  popover: { token: 'background/surface-3' },
  'popover-foreground': { token: 'text/primary' },
  primary: { token: 'background/primary', use: 'bg-primary' },
  'primary-foreground': { token: 'text/on-primary' },
  secondary: { token: 'background/surface-3' },
  'secondary-foreground': { token: 'text/primary' },
  muted: { token: 'background/surface-2' },
  'muted-foreground': { token: 'text/secondary', use: 'text-muted-foreground' },
  accent: { token: 'background/surface-3-hover' },
  'accent-foreground': { token: 'text/primary' },
  // shadcn uses destructive for text, borders and 10–20% tints (like its own dark theme),
  // so it takes Figma's mid error tone. Solid error fills use bg-error.
  destructive: { token: 'border/error' },
  border: { token: 'border/base' },
  input: { token: 'border/input', use: 'border-input' },
  ring: { token: 'border/focus' },
  'chart-1': { token: 'color/maple-500' },
  'chart-2': { token: 'color/juniper-500' },
  'chart-3': { token: 'color/moss-500' },
  'chart-4': { token: 'color/honey-500' },
  'chart-5': { token: 'color/holly-500' },
  sidebar: { token: 'background/surface-2' },
  'sidebar-foreground': { token: 'text/primary' },
  'sidebar-primary': { token: 'background/primary' },
  'sidebar-primary-foreground': { token: 'text/on-primary' },
  'sidebar-accent': { token: 'background/selected' },
  'sidebar-accent-foreground': { token: 'text/primary' },
  'sidebar-border': { token: 'border/subtle' },
  'sidebar-ring': { token: 'border/focus' }
}

/**
 * Figma tokens whose name shadcn owns but whose value equals that shadcn variable's token,
 * so the shadcn utility is used as-is. Verified below — if Figma changes, the build fails.
 */
const SAME_AS_SHADCN = {
  'border/primary': { variable: 'primary', use: 'border-primary' }
}

// Colour names shadcn's theme owns. A Figma key with one of these names would change what a
// shadcn utility means (e.g. --text-color-primary would hijack text-primary), so none is emitted.
const SHADCN_NAMES = new Set(Object.keys(SHADCN))
const NAMESPACE = { background: 'background-color', text: 'text-color', border: 'border-color' }
const PREFIX = { background: 'bg', text: 'text', border: 'border' }

/**
 * The class to use for a Figma colour token. Rule: the Figma name (bg-X / text-X / border-X)
 * unless X is a name shadcn owns — then the shadcn utility that carries the same token.
 */
function classFor(token) {
  const [group, name] = token.name.split('/')
  if (!SHADCN_NAMES.has(name))
    return { utility: `${PREFIX[group]}-${name}`, via: 'figma', own: true }
  const bridged = Object.values(SHADCN).find((s) => s.token === token.name && s.use)
  if (bridged) return { utility: bridged.use, via: 'shadcn', own: false }
  const same = SAME_AS_SHADCN[token.name]
  if (same) {
    const aliasOf = (n) => snap.tokens.colors.find((t) => t.name === n)?.alias
    if (aliasOf(token.name) !== aliasOf(SHADCN[same.variable].token))
      throw new Error(
        `${token.name} no longer equals shadcn --${same.variable}; give it its own mapping`
      )
    return { utility: same.use, via: 'shadcn', own: false }
  }
  throw new Error(`${token.name} collides with shadcn's '${name}' — map it in SHADCN with a 'use'`)
}

// ---------- tokens.css
const lines = ['  /* primitives */']
for (const [name, hex] of Object.entries(snap.primitives.colors))
  lines.push(`  ${v(name)}: ${hex};`)
lines.push('', '  /* semantic colours (aliases keep the primitive chain visible) */')
// An alias can carry an alpha (Figma: alias + opacity), e.g. background/selection = maple-300 @ 20%.
const aliasValue = (t) =>
  t.alpha == null
    ? `var(${v(t.alias)})`
    : `color-mix(in srgb, var(${v(t.alias)}) ${Math.round(t.alpha * 100)}%, transparent)`
for (const t of snap.tokens.colors) lines.push(`  ${v(t.name)}: ${aliasValue(t)};`)
lines.push('', '  /* spacing, radius, border width, icon sizes and stroke, durations */')
for (const t of snap.tokens.numbers) lines.push(`  ${v(t.name)}: ${withUnit(t)};`)
const families = {}
for (const s of snap.textStyles) families[s.name.split('/')[0]] ??= s.family
// The bundled font first: @fontsource-variable registers it as '<Family> Variable'.
const fontStack = (f) => `'${f} Variable', '${f}', ui-sans-serif, system-ui, sans-serif`
lines.push('', '  /* font families (from the Figma text styles) */')
lines.push(`  --ds-font-display: ${fontStack(families.display ?? families.body)};`)
lines.push(`  --ds-font-body: ${fontStack(families.body)};`)
writeFileSync(resolve(OUT, 'tokens.css'), `${HEADER}:root {\n${lines.join('\n')}\n}\n`)

// ---------- theme.css
const theme = []
for (const t of snap.tokens.colors) {
  if (!classFor(t).own) continue
  const [group, name] = t.name.split('/')
  theme.push(`  --${NAMESPACE[group]}-${name}: var(${v(t.name)});`)
}
theme.push(`  --font-display: var(--ds-font-display);`, `  --font-body: var(--ds-font-body);`)

const WEIGHT = {
  Thin: 100,
  'Extra Light': 200,
  Light: 300,
  Regular: 400,
  Medium: 500,
  'Semi Bold': 600,
  Bold: 700,
  'Extra Bold': 800,
  Black: 900
}
const utilities = snap.textStyles.map((s) => {
  const [role] = s.name.split('/')
  const body = [
    `  font-family: var(${role === 'display' ? '--ds-font-display' : '--ds-font-body'});`,
    `  font-size: ${s.size}px;`,
    `  line-height: ${s.lineHeight ? `${s.lineHeight}px` : 'normal'};`,
    `  font-weight: ${WEIGHT[s.style] ?? 400};`
  ]
  if (s.letterSpacingPercent) body.push(`  letter-spacing: ${s.letterSpacingPercent / 100}em;`)
  if (s.textCase === 'UPPER') body.push('  text-transform: uppercase;')
  return `/* ${s.name} — ${s.description} */\n@utility type-${s.name.replace(/\//g, '-')} {\n${body.join('\n')}\n}`
})

writeFileSync(
  resolve(OUT, 'theme.css'),
  `${HEADER}
/*
 * Figma colour tokens that shadcn has no name for: background/X → bg-X, text/X → text-X,
 * border/X → border-X. Additive only — no shadcn utility changes meaning.
 */
@theme inline {
${theme.join('\n')}
}

/* Text styles (Figma text styles → type-* utilities) */
${utilities.join('\n\n')}
`
)

// ---------- shadcn-bridge.css
const radii = snap.tokens.numbers.filter(
  (n) => n.name.startsWith('radius/') && !['none', 'full'].includes(n.name.split('/')[1])
)
writeFileSync(
  resolve(OUT, 'shadcn-bridge.css'),
  `${HEADER}/*
 * Points shadcn's variables at the Figma tokens, re-theming every ui/
 * component (and any added later with \`shadcn add\`) without touching its classes.
 * Imported last by assets/main.css, which keeps shadcn's @theme mapping but no colour values.
 */
:root,
.dark {
${Object.entries(SHADCN)
  .map(([k, { token }]) => `  --${k}: var(${v(token)});`)
  .join('\n')}
  --radius: var(--ds-radius-lg);
}

/* Exact Figma radii instead of shadcn's --radius multipliers; Figma fonts. */
@theme inline {
${radii.map((r) => `  --radius-${r.name.split('/')[1]}: var(${v(r.name)});`).join('\n')}
  --font-sans: var(--ds-font-body);
  --font-heading: var(--ds-font-display);
}
`
)

// ---------- design-system/tokens.generated.ts (data for the DEV catalog)
const data = {
  primitives: Object.entries(snap.primitives.colors).map(([name, value]) => ({
    name,
    value,
    cssVar: v(name)
  })),
  colors: snap.tokens.colors.map((t) => {
    const { utility, via } = classFor(t)
    return {
      name: t.name,
      alias: t.alias,
      alpha: t.alpha,
      description: t.description,
      cssVar: v(t.name),
      utility,
      via
    }
  }),
  shadcn: Object.entries(SHADCN).map(([variable, { token }]) => ({ variable, token })),
  numbers: snap.tokens.numbers.map((t) => ({
    name: t.name,
    value: t.value,
    unit: t.unit ?? 'px',
    cssVar: v(t.name)
  })),
  textStyles: snap.textStyles.map((s) => ({
    name: s.name,
    utility: `type-${s.name.replace(/\//g, '-')}`,
    family: s.family,
    style: s.style,
    size: s.size,
    lineHeight: s.lineHeight,
    description: s.description
  }))
}
const ts = `// GENERATED by scripts/ds/build-tokens.mjs from design/figma/tokens.json — do not edit.
export const TOKENS = ${JSON.stringify(data, null, 2)} as const
`
writeFileSync(
  resolve(ROOT, 'src/renderer/src/design-system/tokens.generated.ts'),
  await prettier.format(ts, {
    ...(await prettier.resolveConfig(resolve(ROOT, 'package.json'))),
    parser: 'typescript'
  })
)

const own = snap.tokens.colors.filter((t) => classFor(t).own).length
console.log(
  `tokens: ${Object.keys(snap.primitives.colors).length} primitives · ${snap.tokens.colors.length} colours (${own} Tailwind keys, ${snap.tokens.colors.length - own} via shadcn) · ${snap.textStyles.length} text styles`
)
